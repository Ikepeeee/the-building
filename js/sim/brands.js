const pick = (a, rng) => a[Math.floor(rng() * a.length)];

export function pickBrand(type, variant, rng) {
  if (type === 'office') {
    const name = pick(OFFICE[variant] || OFFICE.standard, rng);
    if (/事務所|支店|銀行|金庫|証券|編集部|堂|屋/.test(name)) return name;
    const form = pick(OFFICE_FORM, rng);
    return form === '（株）' ? `${name}（株）` : `${form}${name}`;
  }
  if (type === 'condo') return `${pick(SURNAME, rng)}家`;
  if (type.startsWith('hotel')) return pick(HOTEL[variant] || HOTEL.classic, rng);
  return pick(SHOP[variant] || ['テナント'], rng);
}
